// theme
const themeBtn=document.getElementById('themeBtn'),root=document.documentElement;
function applyTheme(t,save){
  root.dataset.theme=t;
  document.querySelector('meta[name=theme-color]').content=(t==='light'?'#f5f6fb':'#090b12');
  themeBtn.setAttribute('aria-pressed',t==='light');
  if(save){try{localStorage.setItem('theme',t);}catch(e){}}
}
applyTheme(root.dataset.theme||'dark');
themeBtn.onclick=()=>{
  root.classList.add('theme-anim');
  applyTheme(root.dataset.theme==='light'?'dark':'light',true);
  setTimeout(()=>root.classList.remove('theme-anim'),450);
};
matchMedia('(prefers-color-scheme: light)').addEventListener('change',e=>{
  let saved=null;try{saved=localStorage.getItem('theme');}catch(_){}
  if(!saved)applyTheme(e.matches?'light':'dark');
});
